  function extractAssignedJson(source, variableName) {
    const assignmentPattern = new RegExp(`${variableName}\\s*=\\s*`, "g");
    let assignment;

    while ((assignment = assignmentPattern.exec(source))) {
      const start = source.indexOf("{", assignmentPattern.lastIndex);

      if (start === -1) {
        continue;
      }

      let depth = 0;
      let inString = false;
      let escaped = false;

      for (let index = start; index < source.length; index += 1) {
        const character = source[index];

        if (inString) {
          if (escaped) {
            escaped = false;
          } else if (character === "\\") {
            escaped = true;
          } else if (character === '"') {
            inString = false;
          }
          continue;
        }

        if (character === '"') {
          inString = true;
        } else if (character === "{") {
          depth += 1;
        } else if (character === "}") {
          depth -= 1;

          if (depth === 0) {
            try {
              return JSON.parse(source.slice(start, index + 1));
            } catch {
              break;
            }
          }
        }
      }
    }

    return null;
  }

