  function parseJson3Transcript(payload) {
    const segments = (payload.events || [])
      .map((event) => ({
        startMs: event.tStartMs || 0,
        durationMs: event.dDurationMs || 0,
        text: (event.segs || []).map((segment) => segment.utf8 || "").join("")
      }))
      .filter((segment) => segment.text.trim())
      .map((segment) => ({
        ...segment,
        text: segment.text.replace(/\s+/g, " ").trim()
      }));

    return {
      transcript: segments.map((segment) => segment.text).join(" ").trim(),
      segmentCount: segments.length
    };
  }

  function parseXmlTranscript(body) {
    const documentNode = new DOMParser().parseFromString(body, "text/xml");

    if (documentNode.querySelector("parsererror")) {
      return { transcript: "", segmentCount: 0 };
    }

    const paragraphNodes = Array.from(documentNode.querySelectorAll("p"));
    const captionNodes = paragraphNodes.length
      ? paragraphNodes
      : Array.from(documentNode.querySelectorAll("text"));
    const segments = captionNodes
      .map((node) => node.textContent.replace(/\s+/g, " ").trim())
      .filter(Boolean);

    return {
      transcript: segments.join(" ").trim(),
      segmentCount: segments.length
    };
  }

  function parseTranscriptBody(body) {
    try {
      const parsed = parseJson3Transcript(JSON.parse(body));

      if (parsed.transcript) {
        return parsed;
      }
    } catch {
      // The original caption URL may return XML instead of JSON.
    }

    return parseXmlTranscript(body);
  }

  function setCaptionFormatWithoutResigning(baseUrl, format) {
    if (/([?&])fmt=[^&]*/.test(baseUrl)) {
      return baseUrl.replace(/([?&])fmt=[^&]*/, `$1fmt=${format}`);
    }

    return `${baseUrl}${baseUrl.includes("?") ? "&" : "?"}fmt=${format}`;
  }

  async function downloadTranscript(track, diagnostics) {
    const json3Url = setCaptionFormatWithoutResigning(track.baseUrl, "json3");
    const runtimeJson3Url = track.runtimeUrl
      ? setCaptionFormatWithoutResigning(track.runtimeUrl, "json3")
      : null;
    const attempts = [
      track.runtimeUrl && { url: track.runtimeUrl, credentials: "include", kind: "runtime" },
      runtimeJson3Url && { url: runtimeJson3Url, credentials: "include", kind: "runtime-json3" },
      { url: json3Url, credentials: "include", kind: "base-json3" },
      { url: track.baseUrl, credentials: "include", kind: "base-original" },
      { url: track.baseUrl, credentials: "omit", kind: "base-original" }
    ]
      .filter(Boolean)
      .filter(
        (attempt, index, allAttempts) =>
          allAttempts.findIndex(
            (candidate) =>
              candidate.url === attempt.url && candidate.credentials === attempt.credentials
          ) === index
      );
    let lastStatus = null;
    let receivedBody = false;

    addDiagnostic(diagnostics, "selected-track", {
      languageCode: track.languageCode,
      languageName: track.languageName,
      isAutoGenerated: track.isAutoGenerated,
      sourceClient: track.sourceClient,
      poProtected: isPoProtectedTrack(track),
      url: summarizeTrackUrl(track.baseUrl),
      runtimeUrl: track.runtimeUrl ? summarizeTrackUrl(track.runtimeUrl) : null
    });

    for (const [index, attempt] of attempts.entries()) {
      let response;

      try {
        response = await fetch(attempt.url, { credentials: attempt.credentials });
      } catch (error) {
        addDiagnostic(diagnostics, "caption-request", {
          attempt: index + 1,
          requestKind: attempt.kind,
          credentials: attempt.credentials,
          networkError: error.message
        });
        continue;
      }

      lastStatus = response.status;

      if (!response.ok) {
        addDiagnostic(diagnostics, "caption-request", {
          attempt: index + 1,
          requestKind: attempt.kind,
          credentials: attempt.credentials,
          status: response.status,
          ok: false,
          bodyLength: null,
          contentType: response.headers?.get?.("content-type") || null
        });
        continue;
      }

      const body = await response.text();

      addDiagnostic(diagnostics, "caption-request", {
        attempt: index + 1,
        requestKind: attempt.kind,
        credentials: attempt.credentials,
        status: response.status,
        ok: true,
        bodyLength: body.length,
        contentType: response.headers?.get?.("content-type") || null
      });

      if (!body.trim()) {
        continue;
      }

      receivedBody = true;
      const parsed = parseTranscriptBody(body);

      addDiagnostic(diagnostics, "caption-parse", {
        attempt: index + 1,
        segmentCount: parsed.segmentCount,
        transcriptLength: parsed.transcript.length
      });

      if (parsed.transcript) {
        return parsed;
      }
    }

    if (!receivedBody) {
      throw new Error(
        lastStatus && lastStatus !== 200
          ? `字幕下载失败（HTTP ${lastStatus}）。`
          : "字幕轨道返回了空内容。"
      );
    }

    throw new Error("字幕格式无法解析或内容为空。");
  }

